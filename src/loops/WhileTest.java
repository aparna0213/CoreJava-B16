package loops;

public class WhileTest {
	public static void main(String[] args) {
		//when we don't know the number of iterations then we will use while loop
		//syntax is same but writing style is different
		int i=0; //initialization
		while(i<10) {//condition
			System.out.println(i);//execution
			i++;//increment or decrement operations
		}
	}

}
